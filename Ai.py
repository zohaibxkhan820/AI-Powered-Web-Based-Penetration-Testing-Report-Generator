# Function to read text from a TXT file
def read_text_from_txt(txt_path):
    try:
        with open(txt_path, "r") as file:
            return file.read()
    except Exception as e:
        print(f"Error reading text from TXT file: {e}")
        return None

# Function to interact with OpenRouter API for analysis
def analyze_with_openrouter(model, text, api_key, site_url=None, site_name=None):
    api_url = "https://openrouter.ai/api/v1/chat/completions"

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": site_url if site_url else "",
        "X-Title": site_name if site_name else "",
    }

    data = {
        "model": model,
        "messages": [
            {
                "role": "user",
                "content": text
            }
        ]
    }

    response = requests.post(api_url, headers=headers, data=json.dumps(data))

    if response.status_code == 200:
        completion = response.json()
        return completion['choices'][0]['message']['content']
    else:
        print(f"Error: {response.status_code}")
        print(response.text)
        return None

# Custom canvas for header and footer
def my_canvas(canvas, doc):
    canvas.saveState()
    # Header
    canvas.setFont("Helvetica-Bold", 12)
    canvas.setFillColor(colors.black)
    canvas.drawCentredString(doc.pagesize[0] / 2, doc.pagesize[1] - 0.75 * inch, "AI Analysis Report")
    # Footer
    canvas.setFont("Helvetica", 10)
    canvas.setFillColor(colors.black)
    footer_text = f"Report Generated by PT-25 on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    canvas.drawCentredString(doc.pagesize[0] / 2, 0.75 * inch, footer_text)
    canvas.restoreState()

# Function to save AI response in a styled PDF
def save_response_in_pdf(ai_response, output_pdf_path):
    if os.path.exists(output_pdf_path):
        os.remove(output_pdf_path)

    c = SimpleDocTemplate(output_pdf_path, pagesize=letter)
    story = []
    styles = getSampleStyleSheet()
    
    # Define custom styles
    styleH = ParagraphStyle(
        name="Heading1",
        fontSize=20,  # Increased size
        fontName="Helvetica-Bold",
        textColor=colors.black,  # Black color
        alignment=TA_CENTER,
        spaceAfter=12
    )
    styleNormal = styles['BodyText']
    
    # Additional styles for specific sections
    styleTitle = ParagraphStyle(name="Title", fontSize=18, alignment=TA_CENTER, spaceAfter=12)
    styleSubtitle = ParagraphStyle(name="Subtitle", fontSize=14, alignment=TA_LEFT, spaceAfter=12, textColor=colors.blue)
    styleText = ParagraphStyle(name="Text", fontSize=12, alignment=TA_LEFT, spaceAfter=8)
    styleIndentedText = ParagraphStyle(name="IndentedText", fontSize=12, alignment=TA_LEFT, leftIndent=20, spaceAfter=8)

    # Add logo
    logo_path = "static/icons/Logo.png"
    if os.path.exists(logo_path):
        logo = Image(logo_path, width=2*inch, height=2*inch)
        logo.hAlign = 'CENTER'
        story.append(logo)
        story.append(Spacer(1, 12))

    # Header with Title
    story.append(Paragraph("Ai Analysis Report By PT-25 a Product by K-Corp", styleH))
    story.append(Spacer(1, 12))
    story.append(Paragraph(f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", styleNormal))
    story.append(PageBreak())

    # Scope Section
    story.append(Paragraph("Scope of Penetration Testing", styleTitle))
    story.append(Spacer(1, 12))
    story.append(Paragraph("The penetration test will include the following phases:", styleText))
    story.append(Spacer(1, 6))
    story.append(Paragraph("- Reconnaissance Phase", styleText))
    story.append(Spacer(1, 6))
    story.append(Paragraph("- Vulnerability Scanning Phase", styleText))
    story.append(Spacer(1, 6))
    story.append(Paragraph("- Website Stress Testing Phase", styleText))
    story.append(PageBreak())

    # AI Analysis Results
    story.append(Paragraph("AI Analysis Results", styleTitle))
    story.append(Spacer(1, 12))
    story.append(Paragraph("The AI response is as follows:", styleSubtitle))

    # Add the analyzed content with custom formatting
    for line in ai_response.splitlines():
        # Color code based on severity
        if "High" in line:
            color = colors.red
        elif "Medium" in line:
            color = colors.orange
        else:
            color = colors.green
        
        # Escape HTML characters to prevent parsing issues
        escaped_line = escape(line)
        # Add the formatted paragraphs with color coding
        story.append(Paragraph(f"<font color='{color}'><b>{escaped_line}</b></font>", styleText))
        story.append(Spacer(1, 6))

    # Build the PDF with custom canvas for header/footer
    c.build(story, onFirstPage=my_canvas, onLaterPages=my_canvas)
    print(f"AI response saved in {output_pdf_path}")

