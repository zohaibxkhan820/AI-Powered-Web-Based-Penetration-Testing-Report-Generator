#!/usr/bin/env python3
import os
import subprocess
import time
import logging
from datetime import datetime
import sys
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, Image
from reportlab.lib.enums import TA_CENTER
import html
import re
from urllib.parse import urlparse

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[logging.StreamHandler()]
)
logger = logging.getLogger('pdf_generator')

# === Get URL from Terminal ===
if len(sys.argv) != 2:
    logger.error("Usage: python3 pdf.py <url>")
    sys.exit(1)
TARGET_URL = sys.argv[1]

# Normalize URL
def normalize_url(url):
    url = url.strip()
    if not url.startswith(('http://', 'https://')):
        url = 'https://' + url
    return url

TARGET_URL = normalize_url(TARGET_URL)

# === Ensure directories exist ===
os.makedirs("outputs", exist_ok=True)
os.makedirs("reports", exist_ok=True)

# === Define script paths and output files ===
scripts = [
    {"name": "Reconnaissance", "script": "info.py", "output": "outputs/recon.txt"},
    {"name": "Vulnerabilities", "script": "vul.sh", "output": "outputs/vul.txt"},
    {"name": "Stress Test", "script": "stress.py", "output": "outputs/stresstest.txt"}
]

# === Clear any existing output files ===
for script in scripts:
    if os.path.exists(script["output"]):
        try:
            os.remove(script["output"])
            logger.info(f"Removed existing output file: {script['output']}")
        except Exception as e:
            logger.error(f"Failed to remove file {script['output']}: {e}")

report_path = "reports/Pentest_Report.pdf"
if os.path.exists(report_path):
    try:
        os.remove(report_path)
        logger.info(f"Removed existing report: {report_path}")
    except Exception as e:
        logger.error(f"Failed to remove report file {report_path}: {e}")

# === Run scripts sequentially ===
def run_script(script_info):
    script_path = script_info["script"]
    output_file = script_info["output"]
    
    logger.info(f"Starting {script_info['name']} phase: {script_path}")
    
    try:
        if script_path.endswith(".py"):
            process = subprocess.run(["python3", script_path, TARGET_URL], 
                                   check=True, 
                                   text=True, 
                                   capture_output=True)
        else:
            process = subprocess.run(["bash", script_path, TARGET_URL], 
                                   check=True, 
                                   text=True, 
                                   capture_output=True)
        
        # Ensure output file exists and has content
        if not os.path.exists(output_file) or os.path.getsize(output_file) == 0:
            with open(output_file, 'w') as f:
                f.write(process.stdout or f"No output generated for {script_info['name']} phase\n")
                logger.info(f"Created output file: {output_file}")
        
        subprocess.run(["sync"])
        
        if os.path.exists(output_file) and os.path.getsize(output_file) > 0:
            logger.info(f"Verified output file: {output_file} (size: {os.path.getsize(output_file)} bytes)")
        else:
            logger.error(f"Output file missing or empty after script execution: {output_file}")
            with open(output_file, 'w') as f:
                f.write(f"No output generated for {script_info['name']} phase\n")
            subprocess.run(["sync"])
            
        return True
    except Exception as e:
        logger.error(f"Error running {script_path}: {str(e)}")
        with open(output_file, 'w') as f:
            f.write(f"Error during {script_info['name']} phase: {str(e)}\n")
        subprocess.run(["sync"])
        return False

# === Execute each script in sequence ===
for script_info in scripts:
    success = run_script(script_info)
    if not success:
        logger.warning(f"Script {script_info['script']} failed but continuing with next phase")

# === HEADER/FOOTER for PDF ===
def add_header_footer(canvas, doc):
    canvas.saveState()
    canvas.setFont('Helvetica-Bold', 10)
    canvas.drawCentredString(A4[0] / 2.0, A4[1] - 30, "Pentest Report")
    canvas.drawCentredString(A4[0] / 2.0, 20, f"Generated by PT-25 on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    canvas.restoreState()

# === PDF GENERATION ===
def generate_pdf():
    logger.info("Starting PDF generation")
    
    story = []
    styles = getSampleStyleSheet()
    styleH = styles['Heading1']
    styleH.alignment = TA_CENTER
    styleSub = styles['Heading2']
    styleNormal = styles['BodyText']

    # === TITLE PAGE WITH LOGO ===
    logo_path = "static/icons/Logo.png"
    if os.path.exists(logo_path):
        img = Image(logo_path, width=180, height=180)
        img.hAlign = 'CENTER'
        story.append(img)
        story.append(Spacer(1, 12))

    centered_style = ParagraphStyle(name='centered', parent=styleNormal, alignment=TA_CENTER)

    story.append(Paragraph("Penetration Test Report", styleH))
    story.append(Paragraph("Generated by PT-25: A Product by K-Corp", centered_style))
    story.append(Spacer(1, 10))
    story.append(Paragraph(f"Target URL: {TARGET_URL}", centered_style))
    story.append(Paragraph(f"Date & Time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", centered_style))
    story.append(PageBreak())

    # === SCOPE SECTION ===
    story.append(Paragraph("Scope of Penetration Testing", styleSub))
    story.append(Paragraph("The following phases are included in this penetration test:", styleNormal))
    for phase in [
        "- Reconnaissance Phase",
        "- Vulnerability Scanning Phase",
        "- Website Stress Testing Phase"
    ]:
        story.append(Paragraph(phase, styleNormal))
    story.append(Spacer(1, 12))

    # === SECTION WRITER ===
    def add_section(title, filepath):
        story.append(Paragraph(title, styleSub))
        if os.path.exists(filepath) and os.path.getsize(filepath) > 0:
            with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    clean_line = html.escape(line.strip())
                    clean_line = re.sub(r'[^\x20-\x7E]+', '', clean_line)
                    clean_line = clean_line[:200] + "..." if len(clean_line) > 200 else clean_line

                    if not clean_line:
                        continue

                    try:
                        if "[High]" in clean_line:
                            story.append(Paragraph(f'<font color="red">{clean_line}</font>', styleNormal))
                        elif "[Medium]" in clean_line:
                            story.append(Paragraph(f'<font color="orange">{clean_line}</font>', styleNormal))
                        elif "[Low]" in clean_line:
                            story.append(Paragraph(f'<font color="blue">{clean_line}</font>', styleNormal))
                        else:
                            story.append(Paragraph(clean_line, styleNormal))
                    except Exception:
                        story.append(Paragraph("[Error displaying line – skipped]", styleNormal))
        else:
            story.append(Paragraph(f"(No data found or empty: {filepath})", styleNormal))
        story.append(Spacer(1, 12))

    # === ADD REPORT SECTIONS ===
    for script_info in scripts:
        add_section(f"{script_info['name']} Section", script_info["output"])

    # === BUILD PDF ===
    try:
        doc = SimpleDocTemplate(report_path, pagesize=A4)
        doc.build(story, onFirstPage=add_header_footer, onLaterPages=add_header_footer)
        logger.info(f"Successfully generated PDF report: {report_path}")
        
        subprocess.run(["sync"])
        
        if os.path.exists(report_path) and os.path.getsize(report_path) > 0:
            logger.info(f"Verified PDF file: {report_path} (size: {os.path.getsize(report_path)} bytes)")
            return True
        else:
            logger.error(f"PDF file missing or empty after generation: {report_path}")
            return False
    except Exception as e:
        logger.error(f"Error generating PDF: {str(e)}")
        return False

# Generate the final PDF report
generate_pdf()

print(f"[✓] Pentest report saved as: {report_path}")